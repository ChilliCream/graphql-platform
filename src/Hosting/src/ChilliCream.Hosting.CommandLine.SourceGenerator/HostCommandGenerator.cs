using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace ChilliCream.Hosting.CommandLine.SourceGenerator;

[Generator(LanguageNames.CSharp)]
public sealed class HostCommandGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var registrations = context.CompilationProvider.Select(GetRegistrations);
        var needsEmbeddedAttribute = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.Assembly.GetTypeByMetadataName("Microsoft.CodeAnalysis.EmbeddedAttribute") is null);
        context.RegisterSourceOutput(registrations.Combine(needsEmbeddedAttribute), static (output, input) =>
        {
            var (calls, addEmbeddedAttribute) = input;
            if (calls is null)
            {
                return;
            }

            if (addEmbeddedAttribute)
            {
                output.AddSource("EmbeddedAttribute.g.cs", """
                    // <auto-generated/>
                    namespace Microsoft.CodeAnalysis
                    {
                        [Embedded]
                        internal sealed partial class EmbeddedAttribute : global::System.Attribute { }
                    }
                    """);
            }

            var source = $$"""
                // <auto-generated/>
                namespace Microsoft.Extensions.Hosting
                {
                    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
                    internal static class GeneratedHostCommandExtensions
                    {
                        public static int RunWithCommands(this global::Microsoft.Extensions.Hosting.IHost host, string[] args)
                            => global::ChilliCream.Hosting.CommandLine.HostCommandRunner.Run(host, args, Configure);

                        public static global::System.Threading.Tasks.Task<int> RunWithCommandsAsync(
                            this global::Microsoft.Extensions.Hosting.IHost host,
                            string[] args,
                            global::System.Threading.CancellationToken cancellationToken = default)
                            => global::ChilliCream.Hosting.CommandLine.HostCommandRunner.RunAsync(host, args, Configure, cancellationToken);

                        private static void Configure(global::System.CommandLine.RootCommand root, global::System.IServiceProvider services)
                        {
                {{calls}}
                        }

                        private static void AddModule<T>(global::System.CommandLine.RootCommand root, global::System.IServiceProvider services)
                            where T : global::ChilliCream.Hosting.CommandLine.IHostCommandModule
                            => T.Configure(root, services);
                    }
                }
                """;

            output.AddSource("HostCommandExtensions.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static string? GetRegistrations(Compilation compilation, CancellationToken cancellationToken)
    {
        var marker = compilation.GetTypeByMetadataName("ChilliCream.Hosting.CommandLine.HostCommandModuleAttribute`1");
        if (marker is null)
        {
            return null;
        }

        var modules = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols.Concat([compilation.Assembly]))
        {
            cancellationToken.ThrowIfCancellationRequested();
            foreach (var attribute in assembly.GetAttributes())
            {
                if (attribute.AttributeClass is { } type
                    && SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, marker))
                {
                    modules.Add(type.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                }
            }
        }

        return string.Join("\n", modules.Select(static module => $"            AddModule<{module}>(root, services);"));
    }
}
